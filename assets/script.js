let currentLanguage = localStorage.getItem("timuraya-language") || "en";

function applyLanguage(lang) {
  const selectedLanguage = translations[lang] ? lang : "en";
  const dictionary = translations[selectedLanguage];

  document.documentElement.lang = selectedLanguage;
  document.title = dictionary.metaTitle;

  if (metaDescription) {
    metaDescription.setAttribute("content", dictionary.metaDescription);
  }

  if (ogTitle) {
    ogTitle.setAttribute("content", dictionary.metaTitle);
  }

  if (ogDescription) {
    ogDescription.setAttribute("content", dictionary.metaDescription);
  }

  if (twitterTitle) {
    twitterTitle.setAttribute("content", dictionary.metaTitle);
  }

  if (twitterDescription) {
    twitterDescription.setAttribute("content", dictionary.metaDescription);
  }

  i18nElements.forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) {
      element.textContent = dictionary[key];
    }
  });

  placeholderElements.forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    if (dictionary[key]) {
      element.setAttribute("placeholder", dictionary[key]);
    }
  });

  languageButtons.forEach((button) => {
    const isActive = button.dataset.langButton === selectedLanguage;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  currentLanguage = selectedLanguage;
  localStorage.setItem("timuraya-language", selectedLanguage);
  updateCalculator();
}

function formatCurrencyIdr(value, lang) {
  if (lang === "id") {
    return new Intl.NumberFormat("id-ID", {
      style: "currency",
      currency: "IDR",
      maximumFractionDigits: 0
    }).format(value);
  }

  return new Intl.NumberFormat("en-US", {
    style: "currency",
    currency: "IDR",
    maximumFractionDigits: 0
  }).format(value);
}

function formatYield(value, lang) {
  const locale = lang === "id" ? "id-ID" : "en-US";
  const unit = lang === "id" ? "ton" : "tons";
  return `${new Intl.NumberFormat(locale, {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2
  }).format(value)} ${unit}`;
}

function formatPercentage(value, lang) {
  const locale = lang === "id" ? "id-ID" : "en-US";
  return `${new Intl.NumberFormat(locale, {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2
  }).format(value)}%`;
}

function formatLandSize(value, lang) {
  const locale = lang === "id" ? "id-ID" : "en-US";
  return `${new Intl.NumberFormat(locale).format(value)} m2`;
}

function formatHectares(value, lang) {
  const locale = lang === "id" ? "id-ID" : "en-US";
  return `${new Intl.NumberFormat(locale, {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2
  }).format(value)} ha`;
}

function formatLiters(value, lang) {
  const locale = lang === "id" ? "id-ID" : "en-US";
  const unit = lang === "id" ? "liter" : "liters";
  return `${new Intl.NumberFormat(locale, {
    maximumFractionDigits: 0
  }).format(value)} ${unit}`;
}

function clampLandSize(value) {
  const numericValue = Number(value) || 1000;
  return Math.min(10000, Math.max(1000, numericValue));
}

function updateCalculator() {
  const landSize = clampLandSize(landInput.value);
  const hectares = landSize / 10000;
  const yieldTons = hectares * calculatorAssumptions.yieldTonsPerHectare;
  const oilLiters = yieldTons * calculatorAssumptions.oilLitersPerTon;
  const revenue = oilLiters * calculatorAssumptions.oilPricePerLiterIdr;
  const packageCost = landSize * calculatorAssumptions.packageCostPerSqmIdr;
  const roi = packageCost > 0 ? (revenue / packageCost) * 100 : 0;
  const landRatio = ((landSize - 1000) / (10000 - 1000)) * 100;
  const yieldRatio = (yieldTons / calculatorAssumptions.yieldTonsPerHectare) * 100;
  const roiRatio = Math.min((roi / 15) * 100, 100);
  const dictionary = translations[currentLanguage];

  landInput.value = String(landSize);
  landRange.value = String(landSize);
  yieldOutput.textContent = formatYield(yieldTons, currentLanguage);
  revenueOutput.textContent = formatCurrencyIdr(revenue, currentLanguage);
  roiOutput.textContent = formatPercentage(roi, currentLanguage);

  if (selectedLandOutput) {
    selectedLandOutput.textContent = formatLandSize(landSize, currentLanguage);
  }
  if (hectaresOutput) {
    hectaresOutput.textContent = formatHectares(hectares, currentLanguage);
  }
  if (oilOutput) {
    oilOutput.textContent = formatLiters(oilLiters, currentLanguage);
  }
  if (tableLandOutput) {
    tableLandOutput.textContent = formatLandSize(landSize, currentLanguage);
  }
  if (tableHectaresOutput) {
    tableHectaresOutput.textContent = formatHectares(hectares, currentLanguage);
  }
  if (tableYieldOutput) {
    tableYieldOutput.textContent = formatYield(yieldTons, currentLanguage);
  }
  if (tableOilOutput) {
    tableOilOutput.textContent = formatLiters(oilLiters, currentLanguage);
  }
  if (packageCostOutput) {
    packageCostOutput.textContent = formatCurrencyIdr(packageCost, currentLanguage);
  }
  if (tableRevenueOutput) {
    tableRevenueOutput.textContent = formatCurrencyIdr(revenue, currentLanguage);
  }
  if (tableRoiOutput) {
    tableRoiOutput.textContent = formatPercentage(roi, currentLanguage);
  }
  if (landBar) {
    landBar.style.width = `${Math.max(landRatio, 10)}%`;
  }
  if (yieldBar) {
    yieldBar.style.width = `${Math.max(yieldRatio, 10)}%`;
  }
  if (roiBar) {
    roiBar.style.width = `${Math.max(roiRatio, 10)}%`;
  }
  if (roiBandOutput && dictionary) {
    if (roi >= 10) {
      roiBandOutput.textContent = dictionary.roiBandStrong;
    } else if (roi >= 7) {
      roiBandOutput.textContent = dictionary.roiBandBalanced;
    } else {
      roiBandOutput.textContent = dictionary.roiBandEarly;
    }
  }
}

function updateHeroVideoState() {
  if (!heroVideo || !heroVideoStage) {
    return;
  }

  const hasPlayableSource =
    heroVideo.readyState >= 2 &&
    Boolean(heroVideo.currentSrc) &&
    !heroVideo.currentSrc.endsWith("/");

  heroVideoStage.classList.toggle("hero-video-live", hasPlayableSource);
}

function updateCommodityPhotoState(isLive) {
  if (!commodityPhotoStage) {
    return;
  }

  commodityPhotoStage.classList.toggle("is-live", Boolean(isLive));
}

